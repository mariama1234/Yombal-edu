# MySQL / MariaDB, surchargeable par variables d'environnement
# (DB_NAME, DB_USER, DB_PASSWORD, DB_HOST, DB_PORT) — aucun secret en dur.
#
# Django 6.1 exige MariaDB 10.11+ ou MySQL 8.0.11+, ce que la MariaDB 10.4
# de XAMPP ne satisfait pas. En local, l'application vise donc une instance
# MariaDB 10.11 dédiée sur le port 3307 ; XAMPP garde le port 3306 pour
# phpMyAdmin et la base de référence gestion_scolaire_ref.
# En production, surcharge DB_PORT (3306 le plus souvent).
#
# `DB_ENGINE=sqlite` bascule sur SQLite, utile si aucun serveur n'est lancé.
if os.environ.get('DB_ENGINE') == 'sqlite':
    DATABASES = {
        'default': {
            'ENGINE': 'django.db.backends.sqlite3',
            'NAME': BASE_DIR / 'db.sqlite3',
        }
    }
else:
    DATABASES = {
        'default': {
            'ENGINE': 'django.db.backends.mysql',
            'NAME': os.environ.get('DB_NAME', 'gestion_scolaire'),
            'USER': os.environ.get('DB_USER', 'root'),
            'PASSWORD': os.environ.get('DB_PASSWORD', ''),
            'HOST': os.environ.get('DB_HOST', '127.0.0.1'),
            'PORT': os.environ.get('DB_PORT', '3307'),
            'OPTIONS': {
                'charset': 'utf8mb4',
                # STRICT_TRANS_TABLES : MySQL refuse les valeurs tronquées au
                # lieu de les accepter silencieusement (montants, matricules).
                'init_command': "SET sql_mode='STRICT_TRANS_TABLES'",
            },
        }
    }


